#!/bin/bash
# Regenerates docs/usage.md with the real output of the plugins on the samples in sample/work and sample/work-6.12.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VOL="${VOL:-$ROOT/.venv/bin/vol}"
run() {  # dir elf args...
  local d="$1" elf="$2"; shift 2
  echo; echo '```'
  echo "\$ vol -p plugins -s isf -f $elf $*"
  (cd "$d" && "$VOL" -q -p "$ROOT/plugins" -s isf -f "$elf" "$@" 2>/dev/null) | sed '/^Volatility 3 Framework/d;/^$/d' | column -t -s $'\t'
  echo '```'
}
{
  echo "# Usage and real output"
  echo
  echo "Generated by \`docs/gen_usage.sh\` with Volatility 3 $("$VOL" --version 2>/dev/null | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)"
  echo "on the release samples. Key serials and PIDs differ between the two dumps (each is a separate boot)."
  for d in "$ROOT/sample/work" "$ROOT/sample/work-6.12"; do
    elf=$(cd "$d" && ls keyring-*.elf); k="${elf#keyring-}"; k="${k%.elf}"
    echo; echo "## Kernel $k"
    echo; echo "### Every key (\`linux.keyring.Keys\`)"
    run "$d" "$elf" linux.keyring.Keys
    echo; echo "### The logon key, dumped (user space gets \"Not supported\" from KEYCTL_READ)"
    tmp=$(mktemp -d)
    echo; echo '```'
    echo "\$ vol -p plugins -s isf -f $elf linux.keyring.Keys --filter '^logon ' --dump"
    (cd "$tmp" && "$VOL" -q -p "$ROOT/plugins" -s "$d/isf" -f "$d/$elf" linux.keyring.Keys --filter '^logon ' --dump 2>/dev/null) | sed '/^Volatility 3 Framework/d;/^$/d' | column -t -s $'\t'
    echo "\$ xxd key-*-logon.bin"
    (cd "$tmp" && xxd key-*-logon.bin)
    echo '```'
    rm -rf "$tmp"
    echo; echo "### Keyrings per task (\`linux.keyring.ProcKeys\`)"
    run "$d" "$elf" linux.keyring.ProcKeys
    echo; echo "### Diff against the guest's own /proc/keys"
    echo; echo '```'
    echo "\$ vol -r json -p plugins -s isf -f $elf linux.keyring.Keys | python3 tools/proc_keys.py > memory.txt"
    echo "\$ grep '^TRUTH view root ' sample/expected/serial-$k.log | cut -c17- > root-view.txt   # what root saw"
    echo "\$ grep -Fxf root-view.txt memory.txt | wc -l; wc -l < root-view.txt"
    mem=$(cd "$d" && "$VOL" -q -r json -p "$ROOT/plugins" -s isf -f "$elf" linux.keyring.Keys 2>/dev/null | python3 "$ROOT/tools/proc_keys.py")
    view=$(grep '^TRUTH view root ' "$ROOT/sample/expected/serial-$k.log" | tr -d '\r' | cut -c17-)
    echo "$(grep -Fxf <(echo "$view") <(echo "$mem") | wc -l | tr -d ' ')"
    echo "$(echo "$view" | wc -l | tr -d ' ')"
    echo '```'
  done
  # the luks-live dump: cryptsetup opened the volume inside the guest (sample/guest-luks)
  d="$ROOT/sample/work-luks"
  if [ -d "$d/isf" ]; then
    elf=$(cd "$d" && ls keyring-*.elf); log="$ROOT/sample/expected/serial-luks-live.log"
    echo; echo "## Live LUKS volume (the luks-live dump, kernel $(basename "${elf#keyring-}" .elf))"
    echo
    echo "cryptsetup 2.7 formatted and opened \`/dev/vda\` inside the guest with \`--link-vk-to-keyring\`. The volume key"
    echo "was drawn in the guest and never printed; the serial log only has its sha256."
    echo; echo "### What the guest saw"
    echo; echo '```'
    echo "\$ grep -E '^TRUTH (table|vk) |cryptsetup:live-vol' sample/expected/serial-luks-live.log"
    grep -E '^TRUTH (table|vk) |cryptsetup:live-vol' "$log" | tr -d '\r'
    echo '```'
    echo; echo "### The key from memory decrypts the disk the guest left behind"
    tmp=$(mktemp -d)
    echo; echo '```'
    echo "\$ vol -p plugins -s isf -f $elf linux.keyring.Keys --filter cryptsetup --dump"
    (cd "$tmp" && "$VOL" -q -p "$ROOT/plugins" -s "$d/isf" -f "$d/$elf" linux.keyring.Keys --filter cryptsetup --dump 2>/dev/null) | sed '/^Volatility 3 Framework/d;/^$/d' | column -t -s $'\t'
    echo "\$ sha256sum key-*-logon.bin   # same digest as the TRUTH vk line above"
    (cd "$tmp" && shasum -a 256 key-*-logon.bin)
    for s in 0 5; do
      echo "\$ python3 tools/luks_vk.py sample/luks/live-vol.img key-*-logon.bin --sector $s | head -1"
      # sed reads to the end: head would close the pipe and pipefail would kill the script
      (cd "$tmp" && python3 "$ROOT/tools/luks_vk.py" "$ROOT/sample/luks/live-vol.img" key-*-logon.bin --sector "$s" 2>&1 | LC_ALL=C tr -d '\0' | LC_ALL=C sed -n "s|$ROOT/||;1,3p")
    done
    echo '```'
    rm -rf "$tmp"
  fi
} > "$ROOT/docs/usage.md"
echo "wrote docs/usage.md"
